/* ═══════════════════════════════════════
   Albexia — i18n.js
   Système de traduction partagé pour toutes les pages du site
   (nav, boutons, footer, kebab menu, éditorial…).

   À inclure sur CHAQUE page HTML publique, AVANT tout script qui
   appelle changerLangue()/appliquerTraductionsStatiques() :

     <script src="/js/i18n.js"></script>

   Ce fichier ne dépend de rien d'autre — pas de Firebase, pas de
   app.js. Il expose sur window :
     - UI_TRANSLATIONS         (dictionnaire brut, si besoin d'y accéder)
     - t(key, langue)          (résout une clé vers son texte)
     - appliquerTraductionsStatiques(langue)  (applique au DOM courant)
     - detecterLangue()        (lit localStorage puis navigator.language)
     - LS_LANG_KEY, LANGUES_SUPPORTEES

   Chaque page reste responsable de : ses propres boutons FR/EN/ES
   (onclick), et de persister + réappliquer la langue quand l'utilisateur
   clique (voir exemple en bas de ce fichier).
   ═══════════════════════════════════════ */

'use strict';

// ─── LANGUE ──────────────────────────────
const LS_LANG_KEY = 'albexia_langue';
const LANGUES_SUPPORTEES = ['fr', 'en', 'es'];

// Détecte la langue à utiliser au chargement d'une page : priorité au
// choix déjà sauvegardé (localStorage, partagé entre toutes les pages
// du site), puis repli sur la langue du navigateur, puis FR par défaut.
function detecterLangue() {
  const saved = localStorage.getItem(LS_LANG_KEY);
  if (saved && LANGUES_SUPPORTEES.includes(saved)) return saved;
  const nav = (navigator.language || 'fr').slice(0, 2).toLowerCase();
  if (LANGUES_SUPPORTEES.includes(nav)) return nav;
  return 'fr';
}
window.detecterLangue = detecterLangue;
window.LS_LANG_KEY = LS_LANG_KEY;
window.LANGUES_SUPPORTEES = LANGUES_SUPPORTEES;

