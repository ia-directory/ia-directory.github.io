// Récupère une clé de traduction pour la langue courante, avec repli sur le
// français si la clé est absente (évite un texte vide en cas d'oubli).
function t(key, langue) {
  const dict = UI_TRANSLATIONS[langue] || UI_TRANSLATIONS.fr;
  return dict[key] ?? UI_TRANSLATIONS.fr[key] ?? key;
}
window.t = t;

// Applique les traductions statiques à tout le DOM courant : texte simple
// (data-i18n), HTML avec balises (data-i18n-html) et placeholders
// d'input (data-i18n-placeholder). À appeler au chargement initial de
// chaque page et à chaque changement de langue.
function appliquerTraductionsStatiques(langue) {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.textContent = t(key, langue);
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    el.innerHTML = t(key, langue);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    el.setAttribute('placeholder', t(key, langue));
  });
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === langue);
  });
  document.documentElement.lang = langue;
}
window.appliquerTraductionsStatiques = appliquerTraductionsStatiques;

// Fonction générique de changement de langue, réutilisable par n'importe
// quelle page (boutons nav, paramètres profil...). Persiste le choix dans
// localStorage (donc partagé par toutes les pages du site) et réapplique
// immédiatement les traductions statiques sur la page courante.
//
// Les pages qui ont du contenu dynamique en plus (ex: index.html avec
// renderTools()/renderBlog()/renderGallery(), ou profil.html avec ses
// propres listes Firestore) doivent définir window.onLangueChange = fn
// AVANT que ce script s'exécute, ou simplement rappeler leurs propres
// fonctions de rendu après avoir appelé changerLangueGlobale().
function changerLangueGlobale(code) {
  if (!LANGUES_SUPPORTEES.includes(code)) return code;
  localStorage.setItem(LS_LANG_KEY, code);
  appliquerTraductionsStatiques(code);
  if (typeof window.onLangueChange === 'function') {
    window.onLangueChange(code);
  }
  return code;
}
window.changerLangueGlobale = changerLangueGlobale;

// Applique automatiquement la langue détectée dès que ce script se charge,
// AVANT même DOMContentLoaded si possible, pour éviter un flash de contenu
// en français sur une page qu'un visiteur EN/ES a déjà configurée. On
// réapplique quand même une fois le DOM prêt, au cas où des éléments
// data-i18n sont ajoutés dynamiquement après coup (ex: contenu Firestore
// avec sa propre logique, ou fragments injectés en JS).
document.addEventListener('DOMContentLoaded', () => {
  appliquerTraductionsStatiques(detecterLangue());
});
